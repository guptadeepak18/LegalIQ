import {
  generateNextAdaptiveQuestion,
  STATIC_ADAPTIVE_QUESTIONS,
  type AssessmentPillar,
  type AssessmentQuestion,
} from "./gemini.js";
import { getPregenQuestion } from "./adaptiveCache.js";
import { logger } from "../lib/logger.js";

// ─── Pillar definitions (used by adaptive engine) ────────────────────────────
const PILLAR_DEFINITIONS: Record<number, string> = {
  1: "Whether the business has active disputes, unresolved claims, or lawsuit exposure",
  2: "Whether written agreements protect the business in all key relationships",
  3: "Whether all government registrations, licences, and filings are current",
  4: "Whether the business spends on legal proactively vs. reactively",
};

// ─── Types ────────────────────────────────────────────────────────────────────

export interface StoredAnswer {
  questionId: string;
  question: string;
  pillar: string;
  pillarIndex: number;
  /** Label of the answer option the user selected */
  answer: string;
  /** Score (0-4) carried by the selected answer option; 4 = healthiest/no risk */
  score: number;
  isSeed: boolean;
  weight: number;
  /** Full question payload as shown to the user — needed to redisplay it when going "back". */
  fullQuestion?: AssessmentQuestion;
  pillarIcon?: string;
  isFollowUp?: boolean;
  /** Session state as it was immediately BEFORE this answer was recorded — restored on "back". */
  prevState?: {
    currentPillarIndex: number;
    currentQuestionIndex: number;
    followUpCount: number;
  };
}

export interface SessionForEngine {
  sessionId: string;
  currentPillarIndex: number;
  currentQuestionIndex: number;
  /** Re-used as adaptiveCount: number of adaptive questions already asked in current pillar */
  followUpCount: number;
  pillars: AssessmentPillar[];
  answers: StoredAnswer[];
  companyName: string;
  businessType: string;
  registration: string;
  employeeCount: string;
  industry: string;
}

export interface SessionAdvance {
  currentPillarIndex?: number;
  currentQuestionIndex?: number;
  followUpCount?: number;
}

export type NextActionResult =
  | {
      type: "QUESTION";
      question: AssessmentQuestion;
      isFollowUp: boolean;
      advanceTo: SessionAdvance;
    }
  | {
      type: "PILLAR_TRANSITION";
      question: AssessmentQuestion;
      completedPillarIndex: number;
      advanceTo: SessionAdvance;
    }
  | { type: "COMPLETE" };

// ─── Main engine ──────────────────────────────────────────────────────────────
//
// TWO-PHASE FLOW PER PILLAR:
//
//  Phase 1 — SEED (always): Ask seed Q1 then seed Q2 in order, no interruptions.
//
//  Phase 2 — ADAPTIVE (always): After all seeds are answered, ask 2–4 adaptive
//  questions generated by AI.  "adaptiveCount" (stored in followUpCount column)
//  tracks how many have been asked.
//    • adaptiveCount < 2  → always ask (mandatory minimum per pillar)
//    • 2 ≤ adaptiveCount < 4 → ask only if AI returns a question
//    • adaptiveCount ≥ 4  → move to next pillar regardless
//
//  Total per pillar: 2 seeds + 2–4 adaptive = 4–6 questions.
//  Grand total: 16–24 questions across 4 pillars.
//
export async function getNextAction(
  session: SessionForEngine
): Promise<NextActionResult> {
  const {
    currentPillarIndex,
    currentQuestionIndex,
    followUpCount: adaptiveCount,
    pillars,
    answers,
    companyName,
    businessType,
    registration,
    employeeCount,
    industry,
  } = session;

  const currentPillar = pillars[currentPillarIndex];
  if (!currentPillar) return { type: "COMPLETE" };

  const lastAnswer = answers[answers.length - 1];
  if (!lastAnswer) return { type: "COMPLETE" };

  // ── Phase 1: Are there more seed questions in this pillar? ──────────────────
  const nextSeedIndex = currentQuestionIndex + 1;
  const nextSeed = currentPillar.questions[nextSeedIndex];

  if (nextSeed) {
    logger.info(
      { pillar: currentPillar.name, seedIndex: nextSeedIndex },
      "Quiz engine: serving next seed question"
    );
    return {
      type: "QUESTION",
      question: nextSeed,
      isFollowUp: false,
      // Seed advance: move questionIndex, reset adaptiveCount for this seed run
      advanceTo: { currentQuestionIndex: nextSeedIndex, followUpCount: 0 },
    };
  }

  // ── Phase 2: Adaptive questions (seeds are exhausted for this pillar) ───────
  // Hard cap: never exceed 4 adaptive per pillar (2 mandatory + 2 optional)
  if (adaptiveCount < 4) {
    const pillarAnswers = answers
      .filter((a) => a.pillarIndex === currentPillarIndex)
      .map((a) => ({
        question: a.question,
        answer: a.answer,
        score: a.score,
      }));

    let adaptiveQ: AssessmentQuestion | null = null;

    // ── PRIORITY 1: Pre-generated business-specific cache (instant, ~0ms) ────
    const cached = getPregenQuestion(session.sessionId, currentPillar.name, adaptiveCount);
    if (cached) {
      logger.info(
        { pillar: currentPillar.name, adaptiveCount },
        "Quiz engine: serving pre-generated business-specific question from cache"
      );
      return {
        type: "QUESTION",
        question: cached,
        isFollowUp: true,
        advanceTo: { followUpCount: adaptiveCount + 1 },
      };
    }

    // ── PRIORITY 2: Per-answer Gemini AI (answer-adaptive, ~3-5s) ─────────
    // Only for mandatory slots (adaptiveCount < 2) where cache missed
    if (adaptiveCount < 2) {
      try {
        adaptiveQ = await generateNextAdaptiveQuestion(
          companyName,
          businessType,
          registration,
          employeeCount,
          industry,
          currentPillar.name,
          currentPillarIndex + 1,
          PILLAR_DEFINITIONS[currentPillarIndex + 1] ?? currentPillar.name,
          pillarAnswers,
          adaptiveCount
        );
      } catch (err) {
        logger.warn({ err }, "Quiz engine: adaptive question failed, will use fallback");
      }
    }

    // ── PRIORITY 3: Static fallback for mandatory slots only ──────────────
    if (!adaptiveQ && adaptiveCount < 2) {
      const pillarNum = currentPillarIndex + 1;
      const fallbacks = STATIC_ADAPTIVE_QUESTIONS[pillarNum];
      const fallback = fallbacks?.[adaptiveCount];
      if (fallback) {
        logger.info(
          { pillar: currentPillar.name, adaptiveCount },
          "Quiz engine: using static fallback for mandatory adaptive slot"
        );
        adaptiveQ = fallback;
      } else {
        logger.warn(
          { pillar: currentPillar.name, adaptiveCount },
          "Quiz engine: no static fallback found — skipping mandatory adaptive"
        );
      }
    }

    if (adaptiveQ) {
      logger.info(
        { pillar: currentPillar.name, adaptiveCount, isStatic: !adaptiveQ.id.includes("_aq") ? false : undefined },
        "Quiz engine: serving adaptive question"
      );
      return {
        type: "QUESTION",
        question: adaptiveQ,
        isFollowUp: true,
        advanceTo: { followUpCount: adaptiveCount + 1 },
      };
    }

    // AI returned null (optional slot, adaptiveCount >= 2). Move to next pillar.
    logger.info(
      { pillar: currentPillar.name, adaptiveAsked: adaptiveCount },
      "Quiz engine: adaptive phase complete"
    );
  }

  // ── Move to next pillar ────────────────────────────────────────────────────
  const nextPillarIndex = currentPillarIndex + 1;

  if (nextPillarIndex < pillars.length) {
    const nextPillar = pillars[nextPillarIndex];
    const firstQ = nextPillar.questions[0];

    if (!firstQ) return { type: "COMPLETE" };

    logger.info(
      {
        completed: currentPillar.name,
        next: nextPillar.name,
        adaptiveAsked: adaptiveCount,
      },
      "Quiz engine: pillar transition"
    );

    return {
      type: "PILLAR_TRANSITION",
      question: firstQ,
      completedPillarIndex: currentPillarIndex,
      advanceTo: {
        currentPillarIndex: nextPillarIndex,
        currentQuestionIndex: 0,
        followUpCount: 0,
      },
    };
  }

  // ── All pillars done ───────────────────────────────────────────────────────
  return { type: "COMPLETE" };
}
